'use strict';
const fs = require('fs');
const path = require('path');
const { open, sleep } = require('./cdp-lib');
const base = JSON.parse(fs.readFileSync(path.join(__dirname, 'save-full.json'), 'utf8'));
const partial = JSON.parse(JSON.stringify(base));
partial.xp = 0;
partial.coins = 500;
partial.stage = 1;
partial.missions = {};
partial.collection = { ownedCharacterIds: ['ilan'], ownedCosmeticIds: [], selectedCharacterId: 'ilan', equipped: {} };
partial.achievements = {};
partial.academic = { answered: 0, correct: 0, wrong: 0, totalTimeMs: 0, sessions: 0, byArea: {}, recent: [] };
(async () => {
  const s = await open({ port: 9367, width: 1280, height: 720, gpu: true });
  await s.seed(partial);
  if (await s.ev("!!document.querySelector('[data-action=menu-continue]')")) await s.click('[data-action="menu-continue"]', 900);
  if (await s.ev("!!document.querySelector('[data-action=backup-off]')")) await s.click('[data-action="backup-off"]', 250);
  await s.key('KeyH'); await sleep(1200);
  await s.shot(path.join(__dirname, '..', 'evidence', 'selector-compra.png'));
  await s.key('ArrowRight'); await sleep(800);
  await s.shot(path.join(__dirname, '..', 'evidence', 'selector-lateral.png'));
  await s.click('[data-action="v2-hero-next"]', 700);
  await s.click('[data-action="v2-hero-next"]', 700);
  await s.click('[data-action="v2-hero-next"]', 700);
  await s.click('[data-action="v2-hero-next"]', 700);
  const txt = await s.text();
  console.log('actions', JSON.stringify(await s.ev("[...document.querySelectorAll('[data-action]')].map(e=>e.getAttribute('data-action')+':'+e.textContent.trim().slice(0,40)).filter(x=>/recruit|select-hero|v2-hero/.test(x)).slice(0,20)")));
  await s.shot(path.join(__dirname, '..', 'evidence', 'selector-bloqueado.png'));
  console.log(txt.slice(0, 700));
  await s.close();
})().catch((e) => { console.error(e); process.exit(1); });
