'use strict';
const fs = require('fs');
const path = require('path');
const { open, sleep } = require('./cdp-lib');
const evidence = path.join(__dirname, '..', 'evidence');
const save = JSON.parse(fs.readFileSync(path.join(__dirname, 'save-world-empty.json'), 'utf8'));
let S = null;
(async () => {
  const s = await open({ port: 9373, width: 960, height: 540, gpu: true });
  S = s;
  await s.seed(save);
  if (await s.ev("!!document.querySelector('[data-action=menu-continue]')")) await s.click('[data-action="menu-continue"]', 900);
  if (await s.ev("!!document.querySelector('[data-action=backup-off]')")) await s.click('[data-action="backup-off"]', 200);
  await s.ev("window.__V2.world.interact('v2w-chest-salud-publica')"); await sleep(400);
  const m1 = await s.ev("(() => { var p=document.querySelector('.v2-world-panel'); var b=document.querySelector('.v2-world-body'); return p?{panel:[p.clientWidth,p.clientHeight],body:[b.scrollHeight,b.clientHeight],viewport:[innerWidth,innerHeight]}:null; })()");
  await s.shot(path.join(evidence, 'w22-cofre-960.png'));
  await s.ev("window.__V2.world.close()"); await sleep(200);
  await s.ev("window.__V2.world.interact('v2w-guide-salud-publica')"); await sleep(400);
  const m2 = await s.ev("(() => { var p=document.querySelector('.v2-world-panel'); var b=document.querySelector('.v2-world-body'); return p?{panel:[p.clientWidth,p.clientHeight],body:[b.scrollHeight,b.clientHeight]}:null; })()");
  await s.shot(path.join(evidence, 'w23-guia-960.png'));
  await s.ev("window.__V2.world.close()"); await sleep(200);
  await s.ev("window.__V2.world.interact('v2w-library')"); await sleep(400);
  const m3 = await s.ev("(() => { var p=document.querySelector('.v2-world-panel'); var b=document.querySelector('.v2-world-body'); return p?{panel:[p.clientWidth,p.clientHeight],body:[b.scrollHeight,b.clientHeight]}:null; })()");
  await s.shot(path.join(evidence, 'w24-biblioteca-960.png'));
  console.log(JSON.stringify({ chest: m1, guide: m2, library: m3, errors: s.errors, network: s.requests.filter(u=>!/^(file|data|blob):/.test(u)) }, null, 2));
  await s.close();
})().catch((e) => { console.error(e); if (S) S.close(); process.exit(1); });
