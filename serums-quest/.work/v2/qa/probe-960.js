'use strict';
const fs = require('fs');
const path = require('path');
const { open, sleep } = require('./cdp-lib');
const save = JSON.parse(fs.readFileSync(path.join(__dirname, 'save-full.json'), 'utf8'));
(async () => {
  const s = await open({ port: 9363, width: 960, height: 540 });
  await s.seed(save);
  if (await s.ev("!!document.querySelector('[data-action=menu-continue]')")) await s.click('[data-action="menu-continue"]', 900);
  await s.key('KeyH'); await sleep(1000);
  await s.shot(path.join(__dirname, '..', 'evidence', 'selector-960.png'));
  await s.key('Escape'); await sleep(400);
  await s.key('KeyJ'); await sleep(700);
  await s.click('[data-action="select-area"][data-area="area-psi-salud-publica"]', 450);
  await s.click('[data-action="select-mission"][data-mission="mission-sp-1"]', 450);
  await s.click('[data-action="start-mission"]', 1200);
  await s.shot(path.join(__dirname, '..', 'evidence', 'duel-960.png'));
  await s.click('[data-action="answer"][data-letter="A"]', 700);
  await s.shot(path.join(__dirname, '..', 'evidence', 'feedback-960.png'));
  console.log('ok', await s.state());
  await s.close();
})().catch((e) => { console.error(e); process.exit(1); });
